#!/usr/bin/env python3
"""wtf_index.py - deterministic catalogue of every iGame3D .wtf model (no LLM needed).

    python3 -I _manifest/tools/wtf_index.py            writes _manifest/WTF_INDEX.md + wtf_index.json

Reads the text header sections of each model (iGame3D Mdl format): bone, vertex, path,
group, edge, material and animation counts, the textures and shaders the materials ask
for, and the animation names. Also lists textures referenced but not present in this
copy (the Images/ folder was not part of the Texts archive).
"""
import json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))           # the old Data/ folder
OUT = os.path.dirname(HERE)
SECTIONS = ('Bones', 'Vertices', 'Paths', 'Groups', 'BoneOrientations', 'Edges', 'Materials', 'Animations')


def read(path):
    raw = open(path, 'rb').read().decode('latin-1')
    return raw.replace('\r\n', '\n').replace('\r', '\n').split('\n')


def parse(path):
    lines = read(path)
    info = {'file': os.path.relpath(path, ROOT), 'bytes': os.path.getsize(path),
            'magic': lines[0].strip() if lines else ''}
    for i, line in enumerate(lines[:8]):
        m = re.match(r'#(Author|Date|Notes|PNG):\s*(.*)', line)
        if m and m.group(2).strip():
            info[m.group(1).lower()] = m.group(2).strip()
    for i, line in enumerate(lines):
        m = re.match(r'#(\w+):\s*$', line)
        if m and m.group(1) in SECTIONS and i + 1 < len(lines):
            try:
                info[m.group(1).lower()] = int(lines[i + 1].split()[0])
            except (ValueError, IndexError):
                pass
    tex, shaders, anims = set(), set(), []
    in_anim = False
    for line in lines:
        s = line.strip()
        if s.startswith('texture='):
            t = s.split(',', 1)[-1].strip()
            if t:
                tex.add(t)
        elif s.startswith('shader='):
            shaders.add(s[7:])
        elif s == '#Animations:':
            in_anim = True
        elif in_anim and re.match(r'^[A-Za-z_][\w .-]*$', s) and not s[0].isdigit() and '=' not in s:
            anims.append(s)
    info['textures'] = sorted(tex)
    if shaders:
        info['shaders'] = sorted(shaders)
    if anims:
        info['animation_names'] = anims[:40]
    return info


def main():
    models = []
    for d, dirs, files in os.walk(ROOT):
        dirs[:] = sorted(x for x in dirs if x not in ('.svn', '_manifest'))
        for f in sorted(files):
            if f.lower().endswith(('.wtf', '.wtf_')):
                models.append(parse(os.path.join(d, f)))
    json.dump(models, open(os.path.join(OUT, 'wtf_index.json'), 'w'), indent=1)
    by_dir = {}
    for m in models:
        by_dir.setdefault(os.path.dirname(m['file']), []).append(m)
    alltex = sorted({t for m in models for t in m['textures']})
    missing = [t for t in alltex if not os.path.exists(os.path.join(os.path.dirname(ROOT), t))
               and not os.path.exists(os.path.join(ROOT, re.sub(r'^Data/', '', t)))]
    o = ['# WTF model index', '',
         'Generated by `_manifest/tools/wtf_index.py` (do not edit by hand). %d models, %.1f MB.'
         % (len(models), sum(m['bytes'] for m in models) / 1e6), '',
         'Columns: verts / bones / materials / animations (names when present). '
         '`!` marks a file that does not start with `iGame3D Mdl`.', '']
    for d in sorted(by_dir):
        ms = by_dir[d]
        o += ['## %s (%d)' % (d, len(ms)), '', '| model | KB | verts | bones | mats | anims | textures |',
              '|---|---|---|---|---|---|---|']
        for m in ms:
            flag = '' if m['magic'] == 'iGame3D Mdl' else ' !'
            an = str(m.get('animations', 0))
            if m.get('animation_names'):
                an += ': ' + ', '.join(m['animation_names'][:6]) + (' ...' if len(m['animation_names']) > 6 else '')
            o.append('| %s%s | %d | %s | %s | %s | %s | %s |' % (
                os.path.basename(m['file']), flag, m['bytes'] // 1024, m.get('vertices', '?'), m.get('bones', 0),
                m.get('materials', '?'), an, ', '.join(os.path.basename(t) for t in m['textures'][:4])
                + (' +%d' % (len(m['textures']) - 4) if len(m['textures']) > 4 else '')))
        o.append('')
    o += ['## Textures referenced (%d) - %d not present in this copy' % (len(alltex), len(missing)), '']
    o += ['- `%s`%s' % (t, '' if t not in missing else ' (missing)') for t in alltex]
    open(os.path.join(OUT, 'WTF_INDEX.md'), 'w').write('\n'.join(o) + '\n')
    print('%d models, %d textures referenced, %d missing' % (len(models), len(alltex), len(missing)))


if __name__ == '__main__':
    sys.exit(main())
