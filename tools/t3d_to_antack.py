#!/usr/bin/env python3
"""t3d_to_antack.py - turn the T3D Antack files into data for the Vibecode3D Antack card.

    python3 tools/t3d_to_antack.py      (run from LIB_GAMES)

Reads T3D_Texts/ (Antack, uDevGame 2002: T3D text models and level files) and writes
Vibecode3D_Games/Antack/antack_data.txt, which Play.Antack reads at start:

  [mesh <name>]            the level terrains as wire meshes, in engine units
  v x y z                  one vertex (shared corners merged)
  e a b                    one edge (1-based vertex numbers)
  [level <name>]           one fight level
  terrain <mesh>
  camera x,y,z             where the player starts
  base0 x,y,z              the player's six hill bases (team 0, player01..06)
  base1 x,y,z              the enemy's six (team 1, player11..16)
  ai <seconds>,<min>,<max> the computer attacks every <seconds>, <min>..<max> armies
  win <level or WON>       where winning leads

Units: T3D world units x 10, with y turned over (Vibecode3D's +Y is down). A T3D model
vertex is model units x scale% / 100 / 1000 in world units, so the hills and bases of a
level line up as they did in T3D; each hill base is set on the ground under it. Everything else (hills, ants, shots) is procedural.
"""
import os, re, sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(HERE, 'T3D_Texts')
OUT = os.path.join(HERE, 'Vibecode3D_Games', 'Antack', 'antack_data.txt')
K = 10.0   # engine units per T3D world unit

# what the load scripts say (checked by hand): attack rhythm and the level a win leads to
LEVELS = {
    'Fight1': ('AntackFight1', (3.0, 1, 3), 'Fight2'),
    'Fight2': ('AntackFight2', (1.5, 2, 4), 'Fight4'),
    'Fight4': ('AntackFight4', (1.5, 2, 4), 'Fight3'),
    'Fight3': ('AntackFight3', (1.0, 2, 4), 'WON'),
    'Trainer': ('AntackTrainer', (4.0, 1, 1), 'WON'),
}


def text(path):
    return open(path, encoding='latin-1').read().replace('\r\n', '\n').replace('\r', '\n')


def mesh(name, offset, scale):
    verts, edges, sec = {}, [], None
    for line in text(os.path.join(SRC, 'Models', name + '.txt')).split('\n'):
        w = line.split()
        if not w:
            continue
        if w[0] in ('VERTICES', 'EDGES', 'UVS', 'END', 'Mesh') or w[0] == 'MATERIAL':
            sec = w[0]
            continue
        if sec == 'VERTICES':
            verts[int(w[0])] = tuple(float(v) for v in w[1:4])
        elif sec == 'EDGES':
            edges.append((int(w[0]), int(w[1])))
    f = scale / 100.0 / 1000.0
    index, out_v, out_e, seen = {}, [], [], set()
    remap = {}
    for i, (x, y, z) in verts.items():
        p = (round((x * f + offset[0]) * K, 1), round(-(y * f + offset[1]) * K, 1), round((z * f + offset[2]) * K, 1))
        if p not in index:
            out_v.append(p)
            index[p] = len(out_v)
        remap[i] = index[p]
    for a, b in edges:
        a, b = remap.get(a), remap.get(b)
        if not a or not b or a == b:
            continue
        key = (min(a, b), max(a, b))
        if key not in seen:
            seen.add(key)
            out_e.append(key)
    return out_v, out_e


def ground(verts, x, z):
    """Terrain height under x,z: the four nearest corners, weighted by nearness. The hills
    are placed on it (in T3D some stood a little above or below the ground)."""
    near = sorted(verts, key=lambda v: (v[0] - x) ** 2 + (v[2] - z) ** 2)[:4]
    w = [1.0 / (1.0 + ((v[0] - x) ** 2 + (v[2] - z) ** 2) ** 0.5) for v in near]
    return round(sum(v[1] * k for v, k in zip(near, w)) / sum(w), 1)


def floats(s):
    return [float(v) for v in s.split(',')]


def main():
    lines = ['# Antack data for Play.Antack. GENERATED by tools/t3d_to_antack.py from T3D_Texts: do not edit.', '']
    meshes = {}
    for name, (folder, ai, win) in LEVELS.items():
        d = os.path.join(SRC, 'Levels', folder)
        lm = text(os.path.join(d, 'level models.txt')).strip().split('\n')[0].split(',')
        terrain, offset, scale = lm[0], floats(','.join(lm[1:4])), float(lm[7])
        if terrain not in meshes:
            meshes[terrain] = mesh(terrain, offset, scale)
        start = [float(v) for v in text(os.path.join(d, 'starting.txt')).split()[:3]]
        bases = {}
        verts = meshes[terrain][0]
        for row in text(os.path.join(d, 'person.txt')).split('\n'):
            w = row.split(',')
            if len(w) > 11 and w[0] == 'hillsite' and re.fullmatch(r'player[01][1-6]', w[11]):
                x, z = float(w[1]) * K, float(w[3]) * K
                bases[w[11]] = (x, ground(verts, x, z), z)
        lines += ['[level %s]' % name, 'terrain ' + terrain,
                  'camera %.1f,%.1f,%.1f' % (start[0] * K, -start[1] * K, start[2] * K)]
        for team in '01':
            for n in range(1, 7):
                b = bases['player%s%d' % (team, n)]
                lines.append('base%s %.1f,%.1f,%.1f' % (team, b[0], b[1], b[2]))
        lines += ['ai %.1f,%d,%d' % ai, 'win ' + win, '']
    for name, (v, e) in meshes.items():
        lines.append('[mesh %s]' % name)
        lines += ['v %s %s %s' % p for p in v]
        lines += ['e %d %d' % p for p in e]
        lines.append('')
        print('%-14s %4d vertices %4d edges' % (name, len(v), len(e)))
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines))
    print('wrote', os.path.relpath(OUT, HERE))


if __name__ == '__main__':
    if any(a in ('-h', '--help') for a in sys.argv[1:]):   # A-50: every tool answers --help
        print(__doc__)
        sys.exit(0)
    main()
